_METRICS_BY_NAME: dict[str, MetricDefinition] = {m.name: m for m in APPROVED_METRICS}


def get_approved_metrics() -> tuple[MetricDefinition, ...]:
    """Return all approved financial metric definitions in display order."""
    return APPROVED_METRICS


def get_metric_definition(metric_name: str) -> MetricDefinition | None:
    """Lookup an approved metric definition by name."""
    return _METRICS_BY_NAME.get(metric_name)
